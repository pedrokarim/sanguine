/**
 * Les six héros, à la main, sur le modèle de Vampire Survivors : des adultes de 32 pixels, petite
 * tête, épaules larges, jambes écartées, bras détachés du corps et un objet à la main.
 *
 * On ne peint ici que les îlots de couleur : le contour noir est ajouté ensuite, tout autour. Une
 * lettre est une teinte, résolue dans `hero.ts` à partir de `HeroArt`, donc une teinte de boutique
 * repeint toujours le personnage.
 */

export type HeroFigure = 'hunter' | 'monk' | 'poacher' | 'witch' | 'nun' | 'count';

export interface FigurePart {
  x: number;
  y: number;
  rows: readonly string[];
  /** Tissu : ses lignes basses ondulent, et traînent derrière le corps à la marche. */
  cloth?: boolean;
}

export interface Figure {
  /** `robe` couvre les jambes ; `dress` les laisse paraître sous une jupe fendue. */
  legs: 'pants' | 'dress' | 'robe';
  hair: readonly [string, string, string];
  trousers?: readonly [string, string, string];
  boots?: readonly [string, string];
  back: readonly FigurePart[];
  /** Le bras libre : il balance à contretemps des jambes. */
  swing: FigurePart;
  upper: readonly FigurePart[];
  dress?: FigurePart;
  feet?: FigurePart;
}

