/**
 * Ce qui tombe au sol : même matière et même contour que les armes (`skillart.ts`).
 *
 * Gemmes et pièces restent petites : il y en a des centaines à l'écran, et elles doivent faire un
 * tapis, pas masquer le combat. Le rang d'une gemme se lit à sa taille et à sa taille de pierre
 * autant qu'à sa couleur : un joueur daltonien doit pouvoir les trier.
 */

const recolor = (rows: ArtRows, swap: Readonly<Record<string, string>>): ArtRows =>
  rows.map((row) => [...row].map((ch) => swap[ch] ?? ch).join(''));

